#!/usr/bin/env python3
"""Copy each shared skill from shared/skills/ into the departments that use it.

A skill several departments need has one source, shared/skills/<skill>/. shared/ is not
a plugin and not a department; shared/manifest.yaml lists, for each shared skill, the
departments that get a copy:

  skills:
    task-stack-workstream: [productivity, accounting, strategy]

Each listed department gets the whole skill at <department>/skills/<skill>/, byte for
byte, so its plugin is complete on its own (ADR 0004). The copy is marked by one extra
file, .shared-copy, naming its source; SKILL.md and every other file stay identical to
the source. Never edit a copy: edit the source and rerun this script.

Rerunning is safe: files are rewritten only when they differ, a file in a copy that the
source no longer has is removed, and a marked copy the manifest no longer lists is
removed whole. A skill folder without the marker (a department's own skill) is never
touched; when one sits where a copy should go, it is reported. While any problem is
reported, nothing is written. Caches (__pycache__,
.pytest_cache, *.pyc) are neither copied nor compared.

After a copy changes in a plugin department, rebuild its commands:
python3 scripts/build_bins.py <department>.

Usage:
  python3 scripts/build_shared.py            write the copies
  python3 scripts/build_shared.py --check    report what would change, change nothing

Exit status: 0 done (or, with --check, nothing to change); 1 with --check when a copy
differs from its source, a listed copy is missing or a marked copy is no longer listed;
1 in either mode when the manifest or a folder is wrong, and then nothing is changed.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = ".shared-copy"
IGNORED_DIRS = {"__pycache__", ".pytest_cache"}
NAME = re.compile(r"^[a-z0-9][a-z0-9-]*$")


def marker_text(skill: str) -> str:
    return (f"Generated by scripts/build_shared.py; do not edit anything in this folder.\n"
            f"source: shared/skills/{skill}\n"
            f"Edit the source and run: python3 scripts/build_shared.py\n")


def copy_source(skill_dir: Path) -> str | None:
    """The shared skill a marked copy names (from its marker), or None for a department's own skill."""
    marker = skill_dir / MARKER
    if not marker.is_file():
        return None
    for line in marker.read_text(encoding="utf-8").splitlines():
        if line.startswith("source: shared/skills/"):
            return line.removeprefix("source: shared/skills/").strip()
    return ""


def parse_manifest(text: str) -> tuple[dict[str, list[str]], list[str]]:
    """Read the manifest's one shape: `skills:`, then `  <skill>: [dept, ...]` or a `- dept` list.

    Kept to the standard library, so the pre-commit check runs on a bare python3."""
    out: dict[str, list[str]] = {}
    problems: list[str] = []
    current: str | None = None
    seen_top = False
    for n, raw in enumerate(text.splitlines(), 1):
        line = re.sub(r"(^|\s)#.*$", "", raw).rstrip()
        if not line.strip():
            continue
        if not line.startswith(" "):
            seen_top = line == "skills:"
            if not seen_top:
                problems.append(f"manifest line {n}: only a top-level 'skills:' is allowed")
            current = None
            continue
        stripped = line.strip()
        if stripped.startswith("- ") and current is not None and line.startswith("    "):
            out[current].append(stripped[2:].strip())
            continue
        m = re.fullmatch(r"  ([^\s:]+):\s*(\[(.*)\])?\s*", line)
        if not seen_top or not m:
            problems.append(f"manifest line {n}: expected '  <skill>: [department, ...]'")
            current = None
            continue
        current = m.group(1)
        if current in out:
            problems.append(f"manifest line {n}: {current} is listed twice")
        out[current] = [d.strip() for d in (m.group(3) or "").split(",") if d.strip()]
    return out, problems


def files_of(folder: Path) -> dict[str, bytes]:
    """Every file under a skill folder by relative path, without caches or the copy marker."""
    out: dict[str, bytes] = {}
    for p in sorted(folder.rglob("*")):
        rel = p.relative_to(folder)
        if not p.is_file() or IGNORED_DIRS & set(rel.parts) or p.suffix == ".pyc" or rel.as_posix() == MARKER:
            continue
        out[rel.as_posix()] = p.read_bytes()
    return out


def load(root: Path) -> tuple[dict[str, list[str]], list[str]]:
    """The manifest, checked against shared/skills/ and the department folders."""
    manifest_path = root / "shared" / "manifest.yaml"
    if not manifest_path.is_file():
        return {}, [f"{manifest_path.relative_to(root)} is missing"]
    manifest, problems = parse_manifest(manifest_path.read_text(encoding="utf-8"))
    sources = {p.parent.name for p in (root / "shared" / "skills").glob("*/SKILL.md")}
    for skill, depts in sorted(manifest.items()):
        if skill not in sources:
            problems.append(f"manifest lists {skill}, which has no shared/skills/{skill}/SKILL.md")
        if not depts:
            problems.append(f"manifest lists no department for {skill}")
        for dept in depts:
            if not NAME.match(dept) or dept == "shared" or not (root / dept).is_dir():
                problems.append(f"manifest gives {skill} to '{dept}', which is not a department folder")
        if len(set(depts)) != len(depts):
            problems.append(f"manifest lists a department twice for {skill}")
    for skill in sorted(sources - set(manifest)):
        problems.append(f"shared/skills/{skill} is in no department; list it in shared/manifest.yaml")
    return manifest, problems


def plan(root: Path = ROOT) -> tuple[list[tuple[str, str]], list[str]]:
    """Actions ("write" a file, "remove" a file, "drop" a whole copy) by path, and problems."""
    manifest, problems = load(root)
    actions: list[tuple[str, str]] = []
    wanted: set[Path] = set()
    for skill, depts in sorted(manifest.items()):
        wanted |= {root / dept / "skills" / skill for dept in depts}
        source = root / "shared" / "skills" / skill
        if not (source / "SKILL.md").is_file():
            continue
        src_files = files_of(source)
        src_files[MARKER] = marker_text(skill).encode()
        for dept in depts:
            if not (root / dept).is_dir():
                continue
            copy = root / dept / "skills" / skill
            rel_copy = copy.relative_to(root).as_posix()
            if copy.is_symlink() or (copy.exists() and not copy.is_dir()):
                problems.append(f"{rel_copy} is not a folder; left alone")
                continue
            if copy.exists() and copy_source(copy) is None:
                problems.append(f"{rel_copy} is the department's own skill (no {MARKER}); left alone")
                continue
            if copy.exists() and copy_source(copy) != skill:
                problems.append(f"{rel_copy}/{MARKER} does not name shared/skills/{skill}; left alone")
                continue
            have = files_of(copy) if copy.exists() else {}
            marker = copy / MARKER
            if marker.is_file():
                have[MARKER] = marker.read_bytes()
            for rel, data in sorted(src_files.items()):
                if have.get(rel) != data:
                    actions.append(("write", f"{rel_copy}/{rel}"))
            for rel in sorted(set(have) - set(src_files)):
                actions.append(("remove", f"{rel_copy}/{rel}"))
    for marker in sorted(root.glob(f"*/skills/*/{MARKER}")):
        copy = marker.parent
        if copy.parent.parent.name == "shared" or copy in wanted:
            continue
        actions.append(("drop", copy.relative_to(root).as_posix()))
    return actions, problems


def apply(actions: list[tuple[str, str]], root: Path = ROOT) -> None:
    for kind, rel in actions:
        p = root / rel
        if kind == "drop":
            shutil.rmtree(p)
        elif kind == "remove":
            p.unlink()
        else:
            skill_dir = root.joinpath(*Path(rel).parts[:3])
            inner = p.relative_to(skill_dir).as_posix()
            data = (marker_text(skill_dir.name).encode() if inner == MARKER
                    else (root / "shared" / "skills" / skill_dir.name / inner).read_bytes())
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
    for kind, rel in actions:  # folders a removed file leaves empty
        if kind == "remove":
            skill_dir = root.joinpath(*Path(rel).parts[:3])
            parent = (root / rel).parent
            while parent != skill_dir and parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
                parent = parent.parent


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Copy shared skills into the departments that use them.")
    parser.add_argument("--check", action="store_true", help="report what would change; change nothing")
    args = parser.parse_args(argv)
    actions, problems = plan(ROOT)
    for kind, rel in actions:
        print(f"{'would ' if args.check else ''}{kind} {rel}")
    for problem in problems:
        print(f"problem: {problem}", file=sys.stderr)
    if args.check:
        print(f"{len(actions)} change(s), {len(problems)} problem(s)")
        return 1 if actions or problems else 0
    if problems:
        print("nothing changed; fix the problems first", file=sys.stderr)
        return 1
    apply(actions, ROOT)
    plugins = sorted({rel.split("/")[0] for _, rel in actions
                      if (ROOT / rel.split("/")[0] / ".claude-plugin" / "plugin.json").is_file()})
    print(f"shared skills copied ({len(actions)} change(s))")
    for dept in plugins:
        print(f"  then: python3 scripts/build_bins.py {dept}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
