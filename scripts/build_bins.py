#!/usr/bin/env python3
"""Build a department plugin's named commands: one wrapper in <department>/bin/ per script.

A department that is a Claude Code plugin (it has .claude-plugin/plugin.json) puts its
bin/ folder on PATH, so a skill says `software-repo-status OWNER/REPO` instead of a path
and an agent's tool rule is `Bash(software-repo-status:*)`.

Every script directly in <department>/skills/<skill>/scripts/ gets a wrapper, except
helper modules (names starting with "_"), templates (".template." in the name) and the
tests/ folder. The wrapper's name is the script's file name without its extension,
underscores turned to hyphens, prefixed "<department>-" unless it already starts so:
repo_status.py in the software department is `software-repo-status`.

A copy of a shared skill (its folder holds .shared-copy; scripts/build_shared.py) is the
exception: its scripts keep one unprefixed name in every department that holds a copy,
so task_stack_apply.py is `task-stack-apply` in accounting and in strategy alike, and the
copy's text stays identical to its source. Two plugins on one PATH then hold wrappers of
the same name that run identical code. A copy's command that clashes with one of the
department's own commands is an error.

A wrapper resolves its own real location (following links), finds the plugin root one
folder up, and runs the script with python3 (.py) or bash (.sh), passing its arguments.

Rerunning is safe: wrappers are rewritten only when they differ, and a wrapper this
script wrote (it carries the marker line) whose script is gone is removed. A file in
bin/ without the marker is never touched; --check reports it.

Usage:
  python3 scripts/build_bins.py DEPARTMENT            write the wrappers
  python3 scripts/build_bins.py --check DEPARTMENT    report what would change, change nothing

Exit status: 0 done (or, with --check, nothing to change); 1 with --check when something
would change, or when two scripts would get the same command name.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = "# Generated by scripts/build_bins.py; do not edit."
RUNNERS = {".py": "python3", ".sh": "bash"}
SHARED_COPY = ".shared-copy"  # build_shared.py's marker in a copied skill's folder


def is_shared_copy(script: Path) -> bool:
    """A script in <skill>/scripts/ whose skill folder is a marked copy of a shared skill."""
    return (script.parent.parent / SHARED_COPY).is_file()


def command_name(department: str, script: Path, shared: bool = False) -> str:
    """repo_status.py -> software-repo-status (in the software department); a shared copy's
    task_stack_apply.py -> task-stack-apply in every department."""
    base = script.name.split(".")[0].replace("_", "-")
    if shared:
        return base
    return base if base.startswith(f"{department}-") else f"{department}-{base}"


def scripts(dept_dir: Path) -> list[Path]:
    """The scripts that become commands: directly in a skill's scripts/, not helpers or templates."""
    found = []
    for p in sorted(dept_dir.glob("skills/*/scripts/*")):
        if p.is_file() and p.suffix in RUNNERS and not p.name.startswith("_") and ".template." not in p.name:
            found.append(p)
    return found


def wrapper_text(dept_dir: Path, script: Path) -> str:
    rel = script.relative_to(dept_dir).as_posix()
    return f"""#!/bin/sh
{MARKER}
# Runs {rel} from this plugin, wherever the plugin is and however this file is linked.
self="$0"
while [ -L "$self" ]; do
  link="$(readlink "$self")"
  case "$link" in
    /*) self="$link" ;;
    *) self="$(dirname "$self")/$link" ;;
  esac
done
root="$(cd "$(dirname "$self")/.." && pwd -P)"
exec {RUNNERS[script.suffix]} "$root/{rel}" "$@"
"""


def wanted(dept_dir: Path) -> tuple[dict[str, str], list[str]]:
    """Map each command name to its wrapper text; list name collisions."""
    out: dict[str, str] = {}
    owner: dict[str, Path] = {}
    problems = []
    for script in scripts(dept_dir):
        name = command_name(dept_dir.name, script, is_shared_copy(script))
        if name in out:
            shared = is_shared_copy(script) or is_shared_copy(owner[name])
            why = " (a shared copy's command clashes with another command)" if shared else ""
            problems.append(f"{name}: both {owner[name].relative_to(ROOT)} and {script.relative_to(ROOT)}{why}")
            continue
        out[name] = wrapper_text(dept_dir, script)
        owner[name] = script
    return out, problems


def plan(dept_dir: Path) -> tuple[list[tuple[str, str]], list[str]]:
    """Actions (write, remove) by command name, and problems (collisions, foreign files, stale wrappers)."""
    want, problems = wanted(dept_dir)
    bin_dir = dept_dir / "bin"
    actions: list[tuple[str, str]] = []
    for name, text in sorted(want.items()):
        p = bin_dir / name
        if p.is_symlink() or (p.exists() and not p.is_file()):
            problems.append(f"{p.relative_to(ROOT)} is not a plain file; left alone")
        elif not p.exists():
            actions.append(("write", name))
        elif p.read_text(encoding="utf-8") != text or not os.access(p, os.X_OK):
            if MARKER in p.read_text(encoding="utf-8"):
                actions.append(("write", name))
            else:
                problems.append(f"{p.relative_to(ROOT)} was not written by build_bins.py; left alone")
    for p in sorted(bin_dir.glob("*")) if bin_dir.is_dir() else []:
        if p.name in want:
            continue
        if p.is_file() and not p.is_symlink() and MARKER in p.read_text(encoding="utf-8", errors="replace"):
            actions.append(("remove", p.name))
        else:
            problems.append(f"{p.relative_to(ROOT)} runs no script in this department's skills")
    return actions, problems


def apply(dept_dir: Path, actions, want: dict[str, str]) -> None:
    bin_dir = dept_dir / "bin"
    bin_dir.mkdir(exist_ok=True)
    for kind, name in actions:
        p = bin_dir / name
        if kind == "remove":
            p.unlink()
        else:
            p.write_text(want[name], encoding="utf-8")
            p.chmod(0o755)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Build a department plugin's bin/ wrappers.")
    parser.add_argument("department", help="the department folder, e.g. software")
    parser.add_argument("--check", action="store_true", help="report what would change; change nothing")
    args = parser.parse_args(argv)
    dept_dir = ROOT / args.department
    if not (dept_dir / "skills").is_dir():
        print(f"error: {args.department} is not a department with a skills/ folder", file=sys.stderr)
        return 2
    actions, problems = plan(dept_dir)
    for kind, name in actions:
        print(f"{'would ' if args.check else ''}{kind} {args.department}/bin/{name}")
    for problem in problems:
        print(f"problem: {problem}", file=sys.stderr)
    if args.check:
        print(f"{len(actions)} change(s), {len(problems)} problem(s)")
        return 1 if actions or problems else 0
    want, _ = wanted(dept_dir)
    apply(dept_dir, actions, want)
    print(f"{len(want)} command(s) in {args.department}/bin/ ({len(actions)} change(s))")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
